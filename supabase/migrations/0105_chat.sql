-- 0105_chat: live chat on Supabase Realtime.
-- channels (public, private, client, dm, group), channel_members (role, notify, last_read_id),
-- messages (threads, mentions, edit/delete, pin, forward, ticket link, files), message_reactions.
--
-- Deviations from the table rules, on purpose:
--  * messages.id is a bigint identity, not a uuid: unread counts, "New" dividers, Seen ticks and
--    reconnect catch-up all compare ids ("messages after the last id"). The client sends a
--    client_key uuid so the realtime echo can replace the optimistic copy.
--  * Attachments live in messages.files (jsonb array of {path, name, mime, size}) instead of a
--    message_files table, so one insert carries them and the realtime row is complete.
--    The bytes are in the private Storage bucket chat-files at <channel_id>/<uuid>-<name>.
--  * channels.client_id has no FK because clients (0108) comes later. 0108 may add:
--    alter table public.channels add constraint channels_client_fk foreign key (client_id) references public.clients (id) on delete cascade;
--  * messages.ticket_key is plain text (tickets is 0106).

-- ---------------------------------------------------------------- channels
create table public.channels (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('public', 'private', 'client', 'dm', 'group')),
  name text, -- null for dm and group; their label is built from the members
  topic text check (length(topic) <= 250),
  client_id uuid,
  admins_only boolean not null default false,
  archived_at timestamptz,
  created_by uuid references public.members (id) on delete set null,
  last_message_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint channels_name_ok check (kind in ('dm', 'group') or name ~ '^[a-z0-9][a-z0-9-]{0,79}$'),
  constraint channels_client_ok check ((kind = 'client') = (client_id is not null))
);
create unique index channels_name_uniq on public.channels (name) where kind in ('public', 'private', 'client');
create index channels_client_idx on public.channels (client_id) where client_id is not null;
create trigger channels_updated_at before update on public.channels
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------- channel_members
create table public.channel_members (
  channel_id uuid not null references public.channels (id) on delete cascade,
  member_id uuid not null references public.members (id) on delete cascade,
  role text not null default 'member' check (role in ('member', 'admin')),
  notify text not null default 'all' check (notify in ('all', 'mentions', 'mute')),
  last_read_id bigint not null default 0,
  created_at timestamptz not null default now(),
  primary key (channel_id, member_id)
);
create index channel_members_member_idx on public.channel_members (member_id);

-- ---------------------------------------------------------------- messages
create table public.messages (
  id bigint generated by default as identity primary key,
  client_key uuid unique,
  channel_id uuid not null references public.channels (id) on delete cascade,
  author_id uuid references public.members (id) on delete set null,
  parent_id bigint references public.messages (id) on delete cascade,
  body text not null default '' check (length(body) <= 8000),
  mentions uuid[] not null default '{}',
  also_in_channel boolean not null default false, -- thread reply also shown in the channel
  forward jsonb, -- {by, ch, text} snapshot of a forwarded message
  files jsonb not null default '[]' check (jsonb_typeof(files) = 'array' and jsonb_array_length(files) <= 10),
  pinned_at timestamptz,
  pinned_by uuid references public.members (id) on delete set null,
  edited_at timestamptz,
  deleted_at timestamptz,
  ticket_key text,
  search_text text generated always as (lower(body || ' ' || jsonb_path_query_array(files, '$[*].name')::text)) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index messages_channel_idx on public.messages (channel_id, id desc);
create index messages_parent_idx on public.messages (parent_id) where parent_id is not null;
create index messages_author_idx on public.messages (author_id);
create trigger messages_updated_at before update on public.messages
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------- message_reactions
-- Composite primary key: realtime DELETE events under RLS carry only the key, which is all we need.
create table public.message_reactions (
  message_id bigint not null references public.messages (id) on delete cascade,
  member_id uuid not null references public.members (id) on delete cascade,
  emoji text not null check (length(emoji) between 1 and 16),
  channel_id uuid not null references public.channels (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (message_id, member_id, emoji)
);
create index message_reactions_channel_idx on public.message_reactions (channel_id);
create index message_reactions_member_idx on public.message_reactions (member_id);

-- ---------------------------------------------------------------- helpers (security definer: no RLS recursion)

-- I am in this conversation and allowed to use chat. Client logins only ever count in their own client's channels.
create or replace function public.is_chat_member(cid uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select public.has_perm('chat.use', 'own') and exists (
    select 1
    from public.channel_members cm
    join public.channels c on c.id = cm.channel_id
    where cm.channel_id = cid and cm.member_id = auth.uid()
      and (public.is_staff() or (c.kind = 'client' and c.client_id = public.my_client_id()))
  );
$$;

-- Same check from a Storage object path "<channel_id>/<file>".
create or replace function public.is_chat_member_path(path text)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.channels c
    where c.id::text = split_part(path, '/', 1) and public.is_chat_member(c.id)
  );
$$;

-- I can manage this conversation: its creator, a channel admin, or a workspace admin.
create or replace function public.is_chat_admin(cid uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select public.is_staff() and public.has_perm('chat.use', 'own') and (
    public.has_perm('admin.access.manage', 'all')
    or exists (select 1 from public.channels c where c.id = cid and c.created_by = auth.uid())
    or exists (select 1 from public.channel_members cm where cm.channel_id = cid and cm.member_id = auth.uid() and cm.role = 'admin')
  );
$$;

-- I can post here (members; admins only when the channel is admins-only).
create or replace function public.can_post_chat(cid uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select public.is_chat_member(cid) and (
    not coalesce((select c.admins_only from public.channels c where c.id = cid), false)
    or public.is_chat_admin(cid)
  );
$$;

-- This person may sit in this conversation: any active staff member, or a client login in its own client's channel.
create or replace function public.chat_member_allowed(cid uuid, mid uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.members m, public.channels c
    where m.id = mid and c.id = cid and m.status in ('active', 'invited')
      and (m.kind = 'staff' or (c.kind = 'client' and m.client_id = c.client_id))
  );
$$;

revoke execute on function public.is_chat_member(uuid), public.is_chat_member_path(text), public.is_chat_admin(uuid),
  public.can_post_chat(uuid), public.chat_member_allowed(uuid, uuid) from public, anon;
grant execute on function public.is_chat_member(uuid), public.is_chat_member_path(text), public.is_chat_admin(uuid),
  public.can_post_chat(uuid), public.chat_member_allowed(uuid, uuid) to authenticated, service_role;

-- Unread and @mention counts per conversation for the signed-in user (RLS applies: security invoker).
-- Counts top-level messages and thread replies also sent to the channel; mentions count everywhere.
create or replace function public.chat_unread()
returns table (channel_id uuid, unread int, mentions int)
language sql stable security invoker
set search_path = ''
as $$
  select cm.channel_id,
    count(*) filter (where m.parent_id is null or m.also_in_channel)::int,
    count(*) filter (where auth.uid() = any (m.mentions))::int
  from public.channel_members cm
  join public.messages m
    on m.channel_id = cm.channel_id and m.id > cm.last_read_id
   and m.deleted_at is null and m.author_id is distinct from auth.uid()
  where cm.member_id = auth.uid()
  group by cm.channel_id;
$$;
revoke execute on function public.chat_unread() from public, anon;
grant execute on function public.chat_unread() to authenticated, service_role;

-- Public channels I have not joined, with member counts (non-members cannot read channel_members).
create or replace function public.chat_browse()
returns table (id uuid, name text, topic text, members int)
language sql stable security definer
set search_path = ''
as $$
  select c.id, c.name, c.topic, (select count(*)::int from public.channel_members x where x.channel_id = c.id)
  from public.channels c
  where c.kind = 'public' and c.archived_at is null
    and public.is_staff() and public.has_perm('chat.use', 'own')
    and not exists (select 1 from public.channel_members cm where cm.channel_id = c.id and cm.member_id = auth.uid())
  order by c.name;
$$;
revoke execute on function public.chat_browse() from public, anon;
grant execute on function public.chat_browse() to authenticated, service_role;

-- ---------------------------------------------------------------- triggers

-- Insert: a reply must sit under a top-level message of the same conversation.
-- Update: only the author edits; only the author or a moderator deletes; ids and authorship never change.
create or replace function public.messages_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.parent_id is not null and not exists (
      select 1 from public.messages p where p.id = new.parent_id and p.channel_id = new.channel_id and p.parent_id is null
    ) then
      raise exception 'Reply must belong to a message in the same conversation' using errcode = '23514';
    end if;
    return new;
  end if;

  if new.channel_id is distinct from old.channel_id or new.author_id is distinct from old.author_id
    or new.parent_id is distinct from old.parent_id or new.client_key is distinct from old.client_key
    or new.forward is distinct from old.forward or new.created_at is distinct from old.created_at then
    raise exception 'These fields cannot change' using errcode = '42501';
  end if;
  if old.deleted_at is not null and auth.uid() is not null then
    raise exception 'This message was deleted' using errcode = '42501';
  end if;

  if new.deleted_at is not null and old.deleted_at is null then
    if auth.uid() is not null and old.author_id is distinct from auth.uid() and not public.is_chat_admin(old.channel_id) then
      raise exception 'Only the author or a moderator can delete this message' using errcode = '42501';
    end if;
    new.body := '';
    new.mentions := '{}';
    new.files := '[]';
    new.forward := null;
    new.pinned_at := null;
    new.pinned_by := null;
    return new;
  end if;

  if new.body is distinct from old.body or new.mentions is distinct from old.mentions
    or new.files is distinct from old.files or new.also_in_channel is distinct from old.also_in_channel then
    if auth.uid() is not null and old.author_id is distinct from auth.uid() then
      raise exception 'Only the author can edit this message' using errcode = '42501';
    end if;
    if new.body is distinct from old.body then
      new.edited_at := now();
    end if;
  end if;
  return new;
end;
$$;
create trigger messages_guard before insert or update on public.messages
  for each row execute function public.messages_guard();

-- After a message: bump the conversation and mark it read for its author.
create or replace function public.messages_after_insert()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  update public.channels set last_message_at = new.created_at where id = new.channel_id;
  update public.channel_members set last_read_id = greatest(last_read_id, new.id)
    where channel_id = new.channel_id and member_id = new.author_id;
  return null;
end;
$$;
create trigger messages_after_insert after insert on public.messages
  for each row execute function public.messages_after_insert();

-- Client logins join their client's channels automatically (on invite and when their client changes).
create or replace function public.chat_join_client_channels()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  if new.kind = 'client' and new.client_id is not null and new.status in ('active', 'invited') then
    insert into public.channel_members (channel_id, member_id)
    select c.id, new.id from public.channels c
    where c.kind = 'client' and c.client_id = new.client_id and c.archived_at is null
    on conflict do nothing;
  end if;
  return null;
end;
$$;
create trigger members_chat_join after insert or update of client_id, kind, status on public.members
  for each row execute function public.chat_join_client_channels();

