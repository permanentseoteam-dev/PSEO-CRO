-- channels: members see theirs; staff also see public channels (to browse and join).
create policy channels_select on public.channels for select to authenticated using (
  public.is_chat_member(id)
  or (kind = 'public' and public.is_staff() and public.has_perm('chat.use', 'own'))
  or (created_by = auth.uid() and public.is_staff())
);
create policy channels_insert on public.channels for insert to authenticated with check (
  public.is_staff() and public.has_perm('chat.use', 'own') and created_by = auth.uid()
);
create policy channels_update on public.channels for update to authenticated
  using (public.is_chat_admin(id)) with check (public.is_chat_admin(id));

-- channel_members: see the people in my conversations; admins add people; staff join public channels;
-- I update my own notify / last_read_id (column grants below) and can leave.
create policy channel_members_select on public.channel_members for select to authenticated using (
  member_id = auth.uid() or public.is_chat_member(channel_id)
);
create policy channel_members_insert on public.channel_members for insert to authenticated with check (
  public.chat_member_allowed(channel_id, member_id)
  and (
    public.is_chat_admin(channel_id)
    or (
      member_id = auth.uid() and role = 'member' and public.is_staff() and public.has_perm('chat.use', 'own')
      and exists (select 1 from public.channels c where c.id = channel_id and c.kind = 'public' and c.archived_at is null)
    )
  )
);
create policy channel_members_update on public.channel_members for update to authenticated
  using (member_id = auth.uid()) with check (member_id = auth.uid());
create policy channel_members_delete on public.channel_members for delete to authenticated using (
  member_id = auth.uid() or public.is_chat_admin(channel_id)
);
revoke update on public.channel_members from authenticated;
grant update (notify, last_read_id) on public.channel_members to authenticated;

-- messages: members read; members post as themselves; field rules in messages_guard. No hard delete.
create policy messages_select on public.messages for select to authenticated using (public.is_chat_member(channel_id));
create policy messages_insert on public.messages for insert to authenticated with check (
  author_id = auth.uid() and public.can_post_chat(channel_id) and deleted_at is null and pinned_at is null
);
create policy messages_update on public.messages for update to authenticated
  using (public.is_chat_member(channel_id)) with check (public.is_chat_member(channel_id));

-- reactions: members read; I add and remove my own.
create policy message_reactions_select on public.message_reactions for select to authenticated using (public.is_chat_member(channel_id));
create policy message_reactions_insert on public.message_reactions for insert to authenticated with check (
  member_id = auth.uid() and public.is_chat_member(channel_id)
  and exists (select 1 from public.messages m where m.id = message_id and m.channel_id = message_reactions.channel_id and m.deleted_at is null)
);
create policy message_reactions_delete on public.message_reactions for delete to authenticated using (member_id = auth.uid());

